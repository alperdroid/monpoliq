import { useQuery } from '@tanstack/react-query';
import { PredictionPanel } from '@/components/dashboard/PredictionPanel';
import { MetricCard } from '@/components/analytics/MetricCard';
import { StanceGauge } from '@/components/analytics/StanceGauge';
import { Skeleton } from '@/components/ui/skeleton';
import { Brain } from 'lucide-react';
import { fedSummary, ecbSummary } from '@/data/mock-data';
import {
  fetchAIPredictions, toPredictionOutput, toCurrencyPrediction,
} from '@/lib/api/predictions';

const Predictions = () => {
  const { data: aiPrediction, isLoading } = useQuery({
    queryKey: ['ai-predictions'],
    queryFn: fetchAIPredictions,
    staleTime: 1000 * 60 * 30,
    retry: 1,
  });

  const fedPred = aiPrediction ? toPredictionOutput(aiPrediction.fed, 'FED') : null;
  const ecbPred = aiPrediction ? toPredictionOutput(aiPrediction.ecb, 'ECB') : null;
  const eurusdPred = aiPrediction ? toCurrencyPrediction(aiPrediction.eurusd) : null;

  return (
    <div className="space-y-6 animate-slide-in max-w-3xl">
      <div>
        <div className="flex items-center gap-2">
          <Brain className="w-5 h-5 text-prediction" />
          <h1 className="text-lg font-semibold">AI Monetary Intelligence</h1>
        </div>
        <p className="text-xs text-muted-foreground mt-1">
          Predictions generated by Gemini AI using live sentiment data, economic indicators, and market signals
        </p>
      </div>

      {isLoading ? (
        <div className="rounded-lg border border-prediction/30 bg-card p-4 space-y-3">
          <div className="flex items-center gap-2">
            <Brain className="w-4 h-4 text-prediction animate-pulse" />
            <span className="text-sm font-semibold">Analyzing data with Gemini...</span>
          </div>
          <Skeleton className="h-24 w-full" />
          <Skeleton className="h-24 w-full" />
          <Skeleton className="h-16 w-full" />
        </div>
      ) : fedPred && ecbPred && eurusdPred ? (
        <PredictionPanel
          fedPrediction={fedPred}
          ecbPrediction={ecbPred}
          currencyPrediction={eurusdPred}
          fedReasoning={aiPrediction?.fed.reasoning}
          ecbReasoning={aiPrediction?.ecb.reasoning}
          eurusdReasoning={aiPrediction?.eurusd.reasoning}
          generatedAt={aiPrediction?.generated_at}
          dataSummary={aiPrediction?.data_summary}
        />
      ) : (
        <div className="rounded-lg border border-destructive/30 bg-card p-4 text-center">
          <p className="text-xs text-muted-foreground">AI predictions unavailable — check your connection and retry</p>
        </div>
      )}

      <div className="rounded-lg border border-border bg-card p-4 space-y-4">
        <h3 className="text-sm font-semibold">Underlying Communication Signals</h3>
        <div className="grid md:grid-cols-2 gap-6">
          <div className="space-y-3">
            <p className="text-xs font-medium text-primary">Federal Reserve</p>
            <StanceGauge value={fedSummary.official_stance} label="Official Stance" />
            <div className="grid grid-cols-2 gap-3">
              <MetricCard label="Guidance" value={`${(fedSummary.guidance_strength * 100).toFixed(0)}%`} />
              <MetricCard label="Uncertainty" value={`${(fedSummary.uncertainty * 100).toFixed(0)}%`} />
              <MetricCard label="Divergence" value={fedSummary.divergence.toFixed(2)} />
              <MetricCard label="Chatter" value={fedSummary.recent_chatter_count} sublabel="30d events" />
            </div>
          </div>
          <div className="space-y-3">
            <p className="text-xs font-medium text-prediction">European Central Bank</p>
            <StanceGauge value={ecbSummary.official_stance} label="Official Stance" />
            <div className="grid grid-cols-2 gap-3">
              <MetricCard label="Guidance" value={`${(ecbSummary.guidance_strength * 100).toFixed(0)}%`} />
              <MetricCard label="Uncertainty" value={`${(ecbSummary.uncertainty * 100).toFixed(0)}%`} />
              <MetricCard label="Divergence" value={ecbSummary.divergence.toFixed(2)} />
              <MetricCard label="Chatter" value={ecbSummary.recent_chatter_count} sublabel="30d events" />
            </div>
          </div>
        </div>
      </div>
    </div>
  );
};

export default Predictions;
